/**
 * OrderQuote Controller
 *
 * POST-BOOKING change quote inquiry API
 *
 * Supports 2 modes:
 * - Mode 1 (SelectedOffer): Seat/service change quote
 * - Mode 2 (RepricedOrderID): Pre-ticketing fare recalculation
 *
 * Workflows:
 * - WF_HELD_SERVICE: OrderRetrieve -> ServiceList -> OrderQuote -> OrderChange
 * - WF_HELD_CONFIRM: OrderRetrieve -> OrderQuote -> OrderChange (SQ, AY, KL)
 * - WF_TKT_SEAT: OrderRetrieve -> SeatAvailability -> OrderQuote -> OrderChange
 * - WF_TKT_SERVICE: OrderRetrieve -> ServiceList -> OrderQuote -> OrderChange
 *
 * CRITICAL:
 * - TransactionID is generated by FE and passed through (pass-through principle)
 * - Same TransactionID must be maintained within the same Post-Booking session
 * - Return raw PolarHub response (no transformation)
 */

import {
  Controller,
  Post,
  Body,
  HttpCode,
  HttpStatus,
  Logger,
  Res,
} from '@nestjs/common';
import { Response } from 'express';
import {
  ApiTags,
  ApiOperation,
  ApiResponse,
  ApiBody,
  ApiExtraModels,
} from '@nestjs/swagger';
import { PolarHubService } from '../polarhub.service';
import {
  OrderQuoteRequestDto,
  OrderQuoteResponseDto,
  SelectedOfferDto,
  RepricedOrderIdDto,
} from '../dto/order-quote.dto';

@ApiTags('order-quote')
@Controller('polarhub/order-quote')
@ApiExtraModels(SelectedOfferDto, RepricedOrderIdDto)
export class OrderQuoteController {
  private readonly logger = new Logger(OrderQuoteController.name);

  constructor(private readonly polarHubService: PolarHubService) {}

  /**
   * OrderQuote - Change quote inquiry
   *
   * Supports 2 modes (mutually exclusive):
   * - Mode 1: selectedOffer - Seat/service quote
   * - Mode 2: repricedOrderId - Delay ticketing fare recalculation
   */
  @Post()
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Get quote for order changes (seat/service or ticketing)',
    description: `OrderQuote API - Change quote inquiry

## 2 Modes

### Mode 1: SelectedOffer (Seat/Service quote)
- **WF_TKT_SEAT**: Seat change quote after ticketing
- **WF_TKT_SERVICE**: Service addition quote after ticketing
- **WF_HELD_SERVICE**: Service addition quote while in Hold status
- Uses OfferID from SeatAvailability or ServiceList response

### Mode 2: RepricedOrderID (Delay ticketing fare recalculation)
- **WF_HELD_CONFIRM**: Fare recalculation before ticketing a Hold booking
- **CRITICAL**: Required for some airlines such as SQ, AY, KL!
- Use the response OfferID in OrderChange AcceptRepricedOrder

## Next Steps
OrderQuote response -> OrderChange (AcceptSelectedQuotedOfferList or AcceptRepricedOrder)

## Transaction ID
- Generated by FE and passed through (middleware generation forbidden)
- Same ID must be maintained within the same Post-Booking session`,
  })
  @ApiBody({ type: OrderQuoteRequestDto })
  @ApiResponse({
    status: 200,
    description: 'Quote retrieved successfully - returns raw PolarHub response',
    type: OrderQuoteResponseDto,
  })
  @ApiResponse({
    status: 400,
    description: 'Invalid request (missing required fields or invalid format)',
  })
  @ApiResponse({
    status: 401,
    description: 'Authentication failed (HMAC signature invalid)',
  })
  @ApiResponse({
    status: 500,
    description: 'Internal server error or PolarHub API error',
  })
  async getOrderQuote(
    @Body() request: OrderQuoteRequestDto,
    @Res({ passthrough: true }) res: Response,
  ): Promise<OrderQuoteResponseDto> {
    // Determine mode
    const mode = this.determineMode(request);

    this.logger.log({
      message: 'OrderQuote request received',
      transactionId: request.transactionId,
      mode,
      orderId: request.orderId,
      hasSelectedOffer: !!request.selectedOffer,
      hasRepricedOrderId: !!request.repricedOrderId,
      hasSender: !!request.sender,
      hasPaxList: !!request.paxList,
      hasAffect: !!request.affect,
      hasCriteria: !!request.criteria,
    });

    // Compose service call parameters
    const serviceParams = {
      transactionId: request.transactionId,
      sender: request.sender
        ? {
            travelAgency: {
              agencyId: request.sender.travelAgency.agencyId,
              siteCode: request.sender.travelAgency.siteCode,
              agencyName: request.sender.travelAgency.agencyName,
              contactInfoRefId: request.sender.travelAgency.contactInfoRefId,
            },
          }
        : undefined,
      orderId: request.orderId,
      // Mode 1: SelectedOffer
      selectedOffer: request.selectedOffer?.map((offer) => ({
        offerId: offer.offerId,
        owner: offer.owner,
        offerItems: offer.offerItems.map((item) => ({
          offerItemId: item.offerItemId,
          paxRefId: item.paxRefId,
          seatSelection: item.seatSelection
            ? {
                column: item.seatSelection.column,
                row: item.seatSelection.row,
              }
            : undefined,
          bookingInstructions: item.bookingInstructions
            ? {
                text: item.bookingInstructions.text,
                ositext: item.bookingInstructions.ositext,
              }
            : undefined,
        })),
        // FopPromotion
        fopPromotion: offer.fopPromotion,
      })),
      // Mode 2: RepricedOrderID (passed as object - maps to Query.RepricedOrderID)
      repricedOrderId: request.repricedOrderId
        ? {
            orderId: request.repricedOrderId.orderId,
            orderItemRefId: request.repricedOrderId.orderItemRefId,
          }
        : undefined,
      // PaxList (with optional birthDate, paxRefId, loyaltyProgramAccount)
      paxList: request.paxList?.map((pax) => ({
        paxId: pax.paxId,
        ptc: pax.ptc,
        birthDate: pax.birthDate,
        paxRefId: pax.paxRefId,
        loyaltyProgramAccount: pax.loyaltyProgramAccount,
      })),
      // Criteria (full CriteriaType4)
      ...(request.criteria && { criteria: request.criteria }),
      // ResponseParameter
      ...(request.responseParameter && { responseParameter: request.responseParameter }),
    };

    const result = await this.polarHubService.getOrderQuote(serviceParams);

    // Set response header
    res.setHeader('X-Transaction-Id', request.transactionId);

    // Return raw response
    return {
      transactionId: result.transactionId,
      response: result.response,
    };
  }

  /**
   * Mode determination helper
   */
  private determineMode(
    request: OrderQuoteRequestDto,
  ): 'SelectedOffer' | 'RepricedOrderID' | 'Unknown' {
    if (
      request.selectedOffer &&
      request.selectedOffer.length > 0
    ) {
      return 'SelectedOffer';
    }
    if (request.repricedOrderId) {
      return 'RepricedOrderID';
    }
    return 'Unknown';
  }
}